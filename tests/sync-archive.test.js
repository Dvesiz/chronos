const assert = require('node:assert/strict');
const fs = require('node:fs');
const SERVER = fs.readFileSync('backend/src/index.js', 'utf8');
const MIGRATION = fs.readFileSync('backend/migrations/0006_sync_devices.sql', 'utf8');
